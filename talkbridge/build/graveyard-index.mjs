#!/usr/bin/env node
/* §7.10 F5 — the graveyard index. Regenerates the one table at the top of
   TALKBRIDGE-GRAVEYARD.md from its `## ` entry headings: id, date, one
   line. Deterministic; run after every burial. `--check` fails if the
   index on disk is stale. */
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const file = path.join(root, 'talkbridge/TALKBRIDGE-GRAVEYARD.md');
const START = '<!-- graveyard-index:start — generated by talkbridge/build/graveyard-index.mjs; do not edit by hand -->';
const END = '<!-- graveyard-index:end -->';
const MONTHS = { jan: '01', feb: '02', mar: '03', apr: '04', may: '05', jun: '06', jul: '07', aug: '08', sep: '09', oct: '10', nov: '11', dec: '12' };
function dateOf(h) {
  let m = h.match(/(20\d\d-\d\d-\d\d)/); if (m) return m[1];
  m = h.match(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\s+(\d{1,2})(?:[–-]\d{1,2})?,?\s+(20\d\d)/i);
  if (m) return m[3] + '-' + MONTHS[m[1].slice(0, 3).toLowerCase()] + '-' + m[2].padStart(2, '0');
  return '';
}
function build(md) {
  const body = md.includes(START) ? md.slice(0, md.indexOf(START) - 1) + md.slice(md.indexOf(END) + END.length + 1) : md;
  const rows = []; let n = 0;
  for (const line of body.split('\n')) {
    if (!line.startsWith('## ') || /^## (Approaches PROVEN|RULE)\b/.test(line)) continue;
    const h = line.slice(3).trim(); n++;
    const g = h.match(/^(G\d+)\b/);
    const id = g ? g[1] : ('E' + String(n).padStart(3, '0'));
    const one = h.replace(/^G\d+\s*[—-]+\s*/, '').replace(/^20\d\d-\d\d-\d\d\s*[—·-]+\s*/, '').replace(/\|/g, '/');
    rows.push('| ' + id + ' | ' + dateOf(h) + ' | ' + one + ' |');
  }
  const table = [START, '<details><summary><b>INDEX — every burial, ' + rows.length + ' entries (id · date · one line). Generated; scan this first.</b></summary>', '', '| id | date | entry |', '|---|---|---|', ...rows, '', '</details>', END].join('\n');
  const anchor = 'Each entry: the approach, its failure signature, what replaces it.';
  const at = body.indexOf(anchor);
  if (at === -1) throw new Error('graveyard anchor paragraph not found');
  const lineEnd = body.indexOf('\n', at);
  return body.slice(0, lineEnd + 1) + '\n' + table + '\n' + body.slice(lineEnd + 1);
}
const md = fs.readFileSync(file, 'utf8');
const out = build(md);
if (process.argv.includes('--check')) { if (out !== md) { console.error('graveyard index is stale — run: node talkbridge/build/graveyard-index.mjs'); process.exit(1); } console.log('graveyard index current'); }
else { fs.writeFileSync(file, out); console.log('graveyard index written: ' + (out.match(/^\| (G\d+|E\d+) \|/gm) || []).length + ' entries'); }
