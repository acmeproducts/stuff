#!/usr/bin/env node
import fs from 'fs'; import { JSDOM } from 'jsdom';
const part = fs.readFileSync('talkbridge/parts/n16-device-log.js', 'utf8');
let fail = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail++; };
const dom = new JSDOM('<body></body>', { url: 'https://x.test/a.html', runScripts: 'outside-only' });
const w = dom.window; const local = []; const posts = []; const store = {};
Object.defineProperty(w.navigator, 'userAgent', { value: 'Mozilla/5.0 (Linux; Android 14)', configurable: true });
Object.defineProperty(w, 'localStorage', { value: { getItem: k => store[k] || null, setItem: (k, v) => { store[k] = v; } }, configurable: true });
w.log = (e, d) => { local.push({ e, d }); return 'orig'; };
w.p3RelayHttp = () => 'https://relay.example/signal';
w.fetch = (u, o) => { posts.push({ u, body: JSON.parse(o.body) }); return Promise.resolve({}); };
w.eval(part);
const before = local.length;
w.log('hello', { a: 1 });
ok(local.length === before + 1 && local[local.length - 1].e === 'hello', 'the local log still receives every line, unchanged');
w.document.dispatchEvent(new w.Event('visibilitychange'));
Object.defineProperty(w.document, 'hidden', { value: true, configurable: true });
w.document.dispatchEvent(new w.Event('visibilitychange'));
await new Promise(r => setTimeout(r, 20));
ok(posts.length >= 1, 'lines are sent to the shared log when the app goes away');
const p0 = posts[posts.length - 1];
ok(/\/log$/.test(p0.u), 'to the relay log endpoint');
ok(/^android-/.test(p0.body.dev), 'tagged with which handset wrote them');
ok(p0.body.rows.some(r => r.e === 'hello' && r.t), 'each line carries its own timestamp, so two devices can be read in order');
w.log('later', {});
ok(local[local.length - 1].e === 'later', 'and logging keeps working after a send');
const relay = fs.readFileSync('talkbridge/worker-talk.js', 'utf8');
ok(relay.includes("url.pathname === '/log'"), 'the relay accepts the shared log');
ok(relay.includes("idFromName('tb::__devicelog__')"), 'in ONE fixed place, so both handsets land in the same file');
ok(relay.includes("while (lines.length > 4000) lines.shift();"), 'and it is bounded so it cannot grow without limit');
const wf = fs.readFileSync('.github/workflows/device-log.yml', 'utf8');
ok(/cron: '\*\/5 \* \* \* \*'/.test(wf), 'the repository drains it on a schedule');
ok(wf.includes('talkbridge/DEVICE-LOG.md'), 'into one file in the repository');
console.log(fail === 0 ? 'N16 GREEN' : fail + ' FAILURES'); process.exit(fail ? 1 : 0);
