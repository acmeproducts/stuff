// End-to-end relay check: a listening page must receive what the watch posts.
// Usage: node e2e.mjs <base-url>
import WebSocket from 'ws';
const base = (process.argv[2] || 'http://127.0.0.1:8787').replace(/\/+$/, '');
const code = String(100000 + Math.floor(Math.random() * 900000));
let fails = 0;
const check = (name, ok, extra = '') => { if (!ok) fails++; console.log((ok ? 'PASS ' : 'FAIL ') + name + (extra ? ' · ' + extra : '')); };
const post = (c, o) => fetch(base + '/e/' + c, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(o) }).then(r => r.json().then(j => ({ status: r.status, j })));

const h = await fetch(base + '/health').then(r => r.json());
check('health answers', h.ok === true, JSON.stringify(h));
const page = await fetch(base + '/').then(r => r.text());
check('the Lab is served at /', page.includes('<title>X · wrist lab</title>'), page.length + ' bytes');
const xpage = await fetch(base + '/x').then(r => r.text());
check('X is served at /x', xpage.includes('<title>X</title>') && !xpage.includes('wrist lab'), xpage.length + ' bytes');
const xl = await fetch(base + '/xlog', { method: 'POST', body: JSON.stringify({ ev: 'e2e', n: 1 }) }).then(r => r.json());
const xlog = await fetch(base + '/log').then(r => r.text());
check('X can write a line to the log', xl.ok === true && xlog.includes('X {"ev":"e2e"'));
check('bad code is refused', (await fetch(base + '/e/12', { method: 'POST', body: '{}' })).status === 404);

const got = [], other = [];
const ws = new WebSocket(base.replace(/^http/, 'ws') + '/s/' + code);
const ws2 = new WebSocket(base.replace(/^http/, 'ws') + '/s/' + (code === '555555' ? '555556' : '555555'));
ws.on('message', d => got.push(String(d)));
ws2.on('message', d => other.push(String(d)));
await Promise.all([new Promise((res, rej) => { ws.on('open', res); ws.on('error', rej); }), new Promise((res, rej) => { ws2.on('open', res); ws2.on('error', rej); })]);
check('page connects', true);
const t0 = Date.now();
const r1 = await post(code, { t: 'swipe', d: 'left', seq: 1 });
check('watch post accepted, one page listening', r1.status === 200 && r1.j.pages === 1, JSON.stringify(r1.j));
await post(code, { t: 'tap', seq: 2 });
await post(code, { t: 'scroll', r: 3, seq: 3 });
await new Promise(r => setTimeout(r, 1200));
check('page received all three, in order', got.length === 3 && got.map(x => JSON.parse(x).seq).join() === '1,2,3', got.join(' | '));
check('another code heard nothing', other.length === 0);
ws.send('ping');
await new Promise(r => setTimeout(r, 600));
check('ping answered', got.includes('pong'));
await new Promise(r => setTimeout(r, 1500));
const log = await fetch(base + '/log').then(r => r.text());
const mine = log.split('\n').filter(l => l.includes('****' + code.slice(-2) + ' '));
check('log holds all three events with the code masked', ['"seq":1', '"seq":2', '"seq":3'].every(k => mine.some(l => l.includes(k))) && !log.includes(code), mine.length + ' lines for this code');
// Lab: a page asks for the raw stream; the watch is told in its next reply; raw rows reach the page but not the log
ws.send(JSON.stringify({ cmd: 'raw', on: 1 }));
await new Promise(r => setTimeout(r, 400));
const r5 = await post(code, { t: 'hb', seq: 5 });
check('page asked for raw: the watch is told', r5.j.raw === 1, JSON.stringify(r5.j));
const before = got.length;
await fetch(base + '/e/' + code, { method: 'POST', body: '{"t":"raw","w":1,"s":[[0,1,2,981,0,0,0,0,0,0]]}' });
await new Promise(r => setTimeout(r, 800));
check('raw rows reach the page', got.slice(before).some(x => x.includes('"t":"raw"')), (got.length - before) + ' new messages');
const log2 = await fetch(base + '/log').then(r => r.text());
check('raw rows are not written to the log', !log2.includes('"t":"raw"'));
ws.send(JSON.stringify({ cmd: 'raw', on: 0 }));
await new Promise(r => setTimeout(r, 400));
check('page stops asking: the watch is told', (await post(code, { t: 'hb', seq: 6 })).j.raw === 0);
// Lab: trials are saved in parts and can be read back
const tid = 'e2e-' + Date.now() + '-check';
const t1 = await fetch(base + '/t/' + code + '/' + tid + '/0', { method: 'POST', body: JSON.stringify({ id: tid, concept: 'e2e', part: 0 }) }).then(r => r.json());
check('trial part saved', t1.ok === true, JSON.stringify(t1));
const list = await fetch(base + '/trials').then(r => r.json());
const mineT = list.filter(x => x.key.startsWith(tid));
check('trial listed', mineT.length === 1 && mineT[0].key === tid + ':000', JSON.stringify(mineT));
const back = await fetch(base + '/trial/' + encodeURIComponent(mineT[0] ? mineT[0].key : 'none')).then(r => r.text());
check('trial read back', back.includes('"concept":"e2e"'));
// ---- W1: sleep and buzz words, last-logged time, hardened pairing, reports ----
const wait = ms => new Promise(r => setTimeout(r, ms));
const pairReq = (c, k) => fetch(base + '/pair/' + c, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ k: k || '' }) }).then(r => r.json().then(j => ({ status: r.status, j })).catch(() => ({ status: r.status, j: {} })));
const wsOpen = (c, k) => new Promise(res => { const w = new WebSocket(base.replace(/^http/, 'ws') + '/s/' + c + (k ? '?k=' + k : '')); w.on('open', () => res({ w, ok: true })); w.on('error', () => res({ ok: false })); w.on('unexpected-response', () => res({ ok: false })); });
// an older watch build sends no key: everything still works, and the page may put the watch to sleep or buzz it
const legacy = await pairReq(code);
check('older watch build: the page pairs without a secret', legacy.status === 200 && legacy.j.legacy === true, JSON.stringify(legacy.j));
ws.send(JSON.stringify({ cmd: 'sleep' }));
await wait(400);
const s1 = await post(code, { t: 'hb', seq: 7 });
check('page says Watch off: the watch is told once', s1.j.sleep === 1 && (await post(code, { t: 'hb', seq: 8 })).j.sleep !== 1, JSON.stringify(s1.j));
ws.send(JSON.stringify({ cmd: 'buzz', p: [0, 40, 60, 40] }));
await wait(400);
const b1 = await post(code, { t: 'hb', seq: 9 });
check('page sends a buzz pattern: the watch gets it once', Array.isArray(b1.j.buzz) && b1.j.buzz.join() === '0,40,60,40' && !(await post(code, { t: 'hb', seq: 10 })).j.buzz, JSON.stringify(b1.j));
ws.send(JSON.stringify({ cmd: 'buzz', p: [0, 5000, 'x'] }));
await wait(300);
check('a bad buzz pattern is dropped', !(await post(code, { t: 'hb', seq: 11 })).j.buzz);
// a watch that sends a key hardens its code
const hc = String(100000 + Math.floor(Math.random() * 900000)), wk = 'k' + Math.random().toString(16).slice(2) + Date.now().toString(16);
const postK = (o, key) => fetch(base + '/e/' + hc, { method: 'POST', headers: Object.assign({ 'content-type': 'application/json' }, key ? { 'x-wrist-key': key } : {}), body: JSON.stringify(o) }).then(r => r.json().then(j => ({ status: r.status, j })).catch(() => ({ status: r.status, j: {} })));
const k1 = await postK({ t: 'diag', why: 'start', seq: 1, up: 1, bat: 80, ln: 'bt', b: 'e2e' }, wk);
check('watch with a key is accepted', k1.status === 200 && k1.j.ok === true, JSON.stringify(k1.j));
check('same code without the key is refused', (await postK({ t: 'hb', seq: 2 })).status === 403);
check('same code with a wrong key is refused', (await postK({ t: 'hb', seq: 2 }, 'nope' + wk)).status === 403);
check('a page cannot listen without a secret', (await wsOpen(hc)).ok === false);
const closed = await pairReq(hc);
check('pairing is refused while the watch has no window open', closed.status === 403 && !closed.j.k, JSON.stringify(closed.j));
await postK({ t: 'hb', seq: 3, up: 4, bat: 80, ln: 'bt', pw: 777 }, wk);
const p1 = await pairReq(hc);
check('window open: the page gets a secret and the last-logged time', p1.status === 200 && typeof p1.j.k === 'string' && p1.j.k.length >= 32 && p1.j.lastDiag > 0, JSON.stringify(p1.j).slice(0, 120));
await postK({ t: 'hb', seq: 4, up: 7, bat: 79, ln: 'bt', pw: 777 }, wk);
check('the same window cannot be used twice', (await pairReq(hc)).status === 403);
const pg = await wsOpen(hc, p1.j.k);
check('the page listens with its secret', pg.ok === true);
check('a made-up secret is refused', (await wsOpen(hc, 'f'.repeat(40))).ok === false);
check('the secret still works on a later visit, with no window', (await pairReq(hc, p1.j.k)).j.k === p1.j.k);
await postK({ t: 'sleep', why: 'page', seq: 5, up: 10, bat: 79, ln: 'bt' }, wk);
const rep = await fetch(base + '/report/' + hc + '?k=' + p1.j.k).then(r => r.json()).catch(() => ({}));
check('report: the session, how it ended, battery at both ends, the panel snapshot', !!rep.sessions && rep.sessions.length === 1 && rep.sessions[0].endWhy === 'page' && rep.sessions[0].bat0 === 80 && rep.sessions[0].bat1 === 79 && rep.snaps.length === 1, JSON.stringify(rep).slice(0, 220));
check('report is refused without the secret', (await fetch(base + '/report/' + hc)).status === 403);
if (pg.w) pg.w.close();
// last, because it blocks further pairing from this address for a minute
let st = 0; for (let i = 0; i < 8; i++) st = (await pairReq(hc)).status;
check('repeated wrong guesses are cut off', st === 429, 'last status ' + st);
console.log('round trip for first post: ' + (Date.now() - t0) + ' ms total incl. waits');
ws.close(); ws2.close();
console.log(fails ? fails + ' relay checks FAILED' : 'all relay checks passed');
setTimeout(() => process.exit(fails ? 1 : 0), 300);
